# Build the Kmux RPM from this checkout and (re)install it with dnf.
# Run from the repository root: ./reinstall_rpm.sh
# Optional: TOPDIR=/path SUDO=doas ./reinstall_rpm.sh

set -euo pipefail

topdir="${TOPDIR:-$HOME/rpmbuild}"
sudo_cmd="${SUDO:-sudo}"

read -r version_major version_minor version_patch prerelease < <(
    awk '
        /^set\(KMUX_VERSION_MAJOR "/  { gsub(/[()"]|set\(KMUX_VERSION_MAJOR /, ""); printf "%s ", $0 }
        /^set\(KMUX_VERSION_MINOR "/  { gsub(/[()"]|set\(KMUX_VERSION_MINOR /, ""); printf "%s ", $0 }
        /^set\(KMUX_VERSION_PATCH "/  { gsub(/[()"]|set\(KMUX_VERSION_PATCH /, ""); printf "%s ", $0 }
        /^set\(KMUX_VERSION_PRERELEASE "/ { gsub(/[()"]|set\(KMUX_VERSION_PRERELEASE /, ""); printf "%s\n", $0 }
    ' CMakeLists.txt
)
version="$version_major.$version_minor.$version_patch"
if [[ -n "$prerelease" ]]; then
    release="0.1.${prerelease}"
else
    release="1"
fi

if [[ -n $(git status --porcelain --untracked-files=no) ]]; then
    echo "Working tree has uncommitted changes; building them via a temporary commit." >&2
    source_ref=$(git stash create) || source_ref=HEAD
    source_ref=${source_ref:-HEAD}
else
    source_ref=HEAD
fi

mkdir -p "$topdir"/{BUILD,BUILDROOT,RPMS,SOURCES,SPECS,SRPMS}
git archive --format=tar.gz --prefix "kmux-$version/" \
    -o "$topdir/SOURCES/kmux-$version.tar.gz" "$source_ref"

cat > "$topdir/SPECS/kmux.spec" << EOF
# Generated by reinstall_rpm.sh; edit the script, not this file.

Name:           kmux
Version:        $version
Release:        $release%{?dist}
Summary:        Project-workspace terminal based on KDE Konsole
License:        GPL-2.0-or-later AND LGPL-2.0-or-later
URL:            https://github.com/teddypickerfromul/kmux
Source0:        %{name}-%{version}.tar.gz

BuildRequires:  cmake
BuildRequires:  desktop-file-utils
BuildRequires:  gcc-c++
BuildRequires:  git
BuildRequires:  kf6-kbookmarks-devel
BuildRequires:  kf6-kconfig-devel
BuildRequires:  kf6-kconfigwidgets-devel
BuildRequires:  kf6-kcoreaddons-devel
BuildRequires:  kf6-kcrash-devel
BuildRequires:  kf6-kdbusaddons-devel
BuildRequires:  kf6-kglobalaccel-devel
BuildRequires:  kf6-kguiaddons-devel
BuildRequires:  kf6-ki18n-devel
BuildRequires:  kf6-kiconthemes-devel
BuildRequires:  kf6-kio-devel
BuildRequires:  kf6-knewstuff-devel
BuildRequires:  kf6-knotifications-devel
BuildRequires:  kf6-knotifyconfig-devel
BuildRequires:  kf6-kparts-devel
BuildRequires:  kf6-kpty-devel
BuildRequires:  kf6-kservice-devel
BuildRequires:  kf6-ktextwidgets-devel
BuildRequires:  kf6-kwidgetsaddons-devel
BuildRequires:  kf6-kwindowsystem-devel
BuildRequires:  kf6-kxmlgui-devel
BuildRequires:  libicu-devel
BuildRequires:  libssh-devel
BuildRequires:  libxkbcommon-devel
BuildRequires:  ninja-build
BuildRequires:  pkgconf-pkg-config
BuildRequires:  qt6-qtbase-devel
BuildRequires:  qt6-qtmultimedia-devel

Requires:       hicolor-icon-theme

%description
Kmux is a terminal for KDE Plasma that groups terminals by project. It is a
fork of Konsole with a cmux-inspired project rail: every project keeps its
own tabs, split views, and running sessions when you switch projects.

%prep
%autosetup -n %{name}-%{version} -p1

%build
%cmake -GNinja \\
    -DCMAKE_BUILD_TYPE=Release \\
    -DBUILD_TESTING=OFF \\
    -DWITH_KAPSULE=OFF \\
    -DWITH_LIBSSH=ON \\
    -Wno-dev
%cmake_build

%install
%cmake_install

(cd "%{buildroot}" && find . \\( -type f -o -type l \\) | sed 's|^\\./|/|') \\
    > "%{_builddir}/%{name}-%{version}.files"

%files -f %{_builddir}/%{name}-%{version}.files
%license COPYING
%license COPYING.LIB
%license LICENSES/CC0-1.0.txt

%changelog
* $(date +'%a %b %d %Y') Yuri <teddypickerfromul@gmail.com> - $version-$release
- Built from kmux checkout $source_ref.
EOF

echo "==> Installing BuildRequires"
"$sudo_cmd" dnf builddep -y "$topdir/SPECS/kmux.spec"

echo "==> Building kmux-$version-$release"
rpmbuild -bb --define "_topdir $topdir" "$topdir/SPECS/kmux.spec"

rpm=$(find "$topdir/RPMS" -name "kmux-*.rpm" ! -name '*debug*' -newer "$topdir/SPECS/kmux.spec" \
    -printf '%T@ %p\n' | sort -rn | cut -d' ' -f2- | head -n1)
[[ -n "$rpm" ]] || { echo "No RPM produced under $topdir/RPMS" >&2; exit 1; }

echo "==> Installing $rpm"
if rpm -q kmux >/dev/null 2>&1; then
    "$sudo_cmd" dnf -y reinstall "$rpm"
else
    "$sudo_cmd" dnf -y install "$rpm"
fi
